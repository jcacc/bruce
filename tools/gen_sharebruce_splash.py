#!/usr/bin/env python3
"""Regenerate src/core/sharebruce_splash.h from media/pictures/sharebruce_splash.png.

Crops to the visible area, scales to HEIGHT px tall, flattens transparency onto
black and emits an RGB565 array for tft.pushImage(). Requires Pillow.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "media/pictures/sharebruce_splash.png"
DST = ROOT / "src/core/sharebruce_splash.h"
HEIGHT = 120  # fits under the title on a 170px-tall screen

im = Image.open(SRC).convert("RGBA")
im = im.crop(im.getchannel("A").getbbox())
w = round(im.width * HEIGHT / im.height)
im = im.resize((w, HEIGHT), Image.LANCZOS)
flat = Image.new("RGBA", im.size, (0, 0, 0, 255))
flat.alpha_composite(im)
px = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r, g, b in flat.convert("RGB").get_flattened_data()]

lines = [
    "// Generated by tools/gen_sharebruce_splash.py - do not edit by hand.",
    "#pragma once",
    "#include <Arduino.h>",
    "",
    f"#define sharebruce_splash_width {w}",
    f"#define sharebruce_splash_height {HEIGHT}",
    "static const uint16_t sharebruce_splash[] PROGMEM = {",
]
for i in range(0, len(px), 12):
    lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i : i + 12]) + ",")
lines.append("};")
DST.write_text("\n".join(lines) + "\n")
print(f"wrote {DST} ({w}x{HEIGHT})")
