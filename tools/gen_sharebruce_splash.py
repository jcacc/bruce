#!/usr/bin/env python3
"""Regenerate src/core/sharebruce_splash.h from media/pictures/sharebruce_splash.png.

Crops to the visible area, scales to HEIGHT px tall, and emits an RGB565 array for
tft.pushImage() with a transparent colour key: originally-transparent pixels become
TRANSP (magenta, which never occurs in the figure) so the boot screen can draw the
figure without a black background box. Opaque pixels keep their own colour, so black
outlines/eyes stay black. Requires Pillow.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "media/pictures/sharebruce_splash.png"
DST = ROOT / "src/core/sharebruce_splash.h"
HEIGHT = 120   # fits under the title on a 170px-tall screen
TRANSP = 0xF81F  # magenta key: skipped by pushImage; absent from the artwork
ALPHA_CUTOFF = 128  # pixels less opaque than this are treated as transparent


def to565(r, g, b):
    v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    # Never let a real pixel collide with the transparency key.
    return v if v != TRANSP else (TRANSP ^ 0x1)


im = Image.open(SRC).convert("RGBA")
im = im.crop(im.getchannel("A").getbbox())
w = round(im.width * HEIGHT / im.height)
im = im.resize((w, HEIGHT), Image.LANCZOS)

px = []
for r, g, b, a in im.get_flattened_data():
    px.append(TRANSP if a < ALPHA_CUTOFF else to565(r, g, b))

lines = [
    "// Generated by tools/gen_sharebruce_splash.py - do not edit by hand.",
    "#pragma once",
    "#include <Arduino.h>",
    "",
    f"#define sharebruce_splash_width {w}",
    f"#define sharebruce_splash_height {HEIGHT}",
    f"#define sharebruce_splash_transp 0x{TRANSP:04X}  // transparent colour key",
    "static const uint16_t sharebruce_splash[] PROGMEM = {",
]
for i in range(0, len(px), 12):
    lines.append("    " + ", ".join(f"0x{v:04X}" for v in px[i : i + 12]) + ",")
lines.append("};")
DST.write_text("\n".join(lines) + "\n")
print(f"wrote {DST} ({w}x{HEIGHT}), transp=0x{TRANSP:04X}")
